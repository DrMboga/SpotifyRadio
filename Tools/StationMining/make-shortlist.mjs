import { readFileSync, writeFileSync } from 'node:fs';

const S = process.argv[2];
const all = [
  ...JSON.parse(readFileSync(`${S}/us-probed.json`, 'utf8')),
  ...JSON.parse(readFileSync(`${S}/us2c-probed.json`, 'utf8')),
].filter((r) => r.alive);

// De-dupe: KRBE was probed from both the researched list and the partial scrape.
const seen = new Set();
const alive = all.filter((r) => {
  const key = r.url.replace(/^https?:\/\//, '').split('?')[0];
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const isRock = (r) => /rock|metal|punk|alternative|80s/i.test(`${r.genres} ${r.icyGenre}`);
const rock = alive.filter(isRock);
const pop = alive.filter((r) => !isRock(r));

// §5.2: MP3 is the lighter decoder on a board with no RAM to spare, so sort it
// to the top where the choice is otherwise a wash.
const rank = (a, b) => (a.codec === b.codec ? 0 : a.codec === 'mp3' ? -1 : 1);
rock.sort(rank);
pop.sort(rank);

// The DB separates genres with "|", which would break the markdown table.
const esc = (s) => String(s ?? '').replace(/\|/g, ' / ');
// The ICY name is what the server calls itself, and it is the check on
// everything else: where it disagrees with the candidate name, the URL points
// at a different station than the label claims.
const row = (r) => `| ${esc(r.name)} | ${esc(r.icyName) || '—'} | ${r.codec.toUpperCase()}${r.bitrate ? ' ' + r.bitrate + 'k' : ''} | ${esc(r.genres || r.icyGenre)} | \`${r.url}\` |`;
const header = '| Station | Server says (ICY) | Codec | Genre | Stream URL |\n|---|---|---|---|---|';

const md = `# USA shortlist — probe-verified

Every row below answered from this machine (Germany) with a usable audio
\`Content-Type\`. Generated by \`probe.mjs\`; re-run it before committing any of
these to \`stations.csv\`, since stream URLs rot.

**MP3 rows are listed first on purpose** (§5.2): AAC costs more RAM on a board
that has none to spare, so where two stations are equally good, take the MP3.

**Check the "Server says" column against the station name.** Where they
disagree the URL points somewhere other than the label claims — the URL
circulating as KNAC.com identifies itself as *J-Pop Powerplay Kawaii*, so it is
alive but it is not KNAC.

The iHeart-hosted rows (\`stream.revma.ihrhls.com\`) redirect through a token
before the audio starts, and one or two of them fail a given probe run and pass
the next. Re-run before trusting a single "dead" result on those.

## Rock / Metal (${rock.length})

${header}
${rock.map(row).join('\n')}

## Pop / other (${pop.length})

${header}
${pop.map(row).join('\n')}
`;

writeFileSync('Tools/StationMining/us-shortlist.md', md);
console.log(`rock=${rock.length} pop=${pop.length} total=${alive.length}`);
